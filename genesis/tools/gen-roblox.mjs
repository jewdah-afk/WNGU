// Emits the Roblox build's generated modules from the JS sources of truth:
//   roblox/src/shared/Content.luau    content spec with explicit key orders
//   roblox/src/shared/AtlasData.luau  pre-baked sprites (palette + RLE, base64)
//   roblox/tests/Fixture.luau         bot session command log + state hashes
// Usage: node tools/gen-roblox.mjs
import fs from "node:fs";
import * as C from "../games/factory-universe/content.js";
import { bake, scaleGenome } from "../engine/pixel/raster.js";
import { GENOMES, ITEM_GENOMES, TILE_GENOMES, oreGenome } from "../games/factory-universe/art.js";
import { createWorld, step, stateHash, terrainHash } from "../engine/sim/factory.js";
import { starterFactory, scienceBlock } from "../qa/bot.mjs";

const RB = "games/factory-universe/roblox";
const HEADER = "-- GENERATED by tools/gen-roblox.mjs from the JS sources. Do not edit by hand.\n";

// ---------- JS value -> Luau literal ----------
const ident = k => /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) && !["and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while"].includes(k);
function lua(v, ind = "") {
  if (v === null || v === undefined) return "nil";
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  const n = ind + "\t";
  if (Array.isArray(v)) return v.length ? "{ " + v.map(x => lua(x, n)).join(", ") + " }" : "{}";
  const ks = Object.keys(v).filter(k => v[k] !== undefined);
  if (!ks.length) return "{}";
  return "{\n" + ks.map(k => `${n}${ident(k) ? k : `[${JSON.stringify(k)}]`} = ${lua(v[k], n)},`).join("\n") + `\n${ind}}`;
}

// ---------- Content.luau ----------
const recipes = {};
for (const k of Object.keys(C.RECIPES)) {
  const r = C.RECIPES[k];
  recipes[k] = { machine: r.machine, time: r.time, inputs: r.in, inOrder: Object.keys(r.in), out: r.out, outOrder: Object.keys(r.out), tech: r.tech };
}
const buildings = {};
for (const k of Object.keys(C.BUILDINGS)) {
  const b = { ...C.BUILDINGS[k] };
  b.cost = b.cost || {}; b.costOrder = Object.keys(b.cost);
  buildings[k] = b;
}
const content = {
  TPS: C.TPS, COAL_KJ: C.COAL_KJ, BELT: C.BELT, ORES: C.ORES,
  ITEM_ORDER: Object.keys(C.ITEMS), ITEMS: C.ITEMS,
  RECIPE_ORDER: Object.keys(C.RECIPES), RECIPES: recipes,
  BUILDING_ORDER: Object.keys(C.BUILDINGS), BUILDINGS: buildings,
  TECH_ORDER: Object.keys(C.TECHS), TECHS: C.TECHS,
  START_STOCK: C.START_STOCK, START_ORDER: Object.keys(C.START_STOCK),
};
fs.mkdirSync(`${RB}/src/shared`, { recursive: true });
fs.writeFileSync(`${RB}/src/shared/Content.luau`, HEADER + "return " + lua(content) + "\n");

// ---------- AtlasData.luau ----------
// Each sprite: palette of packed ABGR u32 (WritePixelsBuffer layout) + runs of
// (palette index, length<=255) bytes. Index 0 is always fully transparent.
const FRAMES = 4, BELT_FRAMES = 8;
const sprites = [];
function add(key, s) {
  const pal = [0], idx = new Map([[0, 0]]), bytes = [];
  let prev = -1, run = 0;
  const flush = () => { if (run) { bytes.push(prev, run); run = 0; } };
  for (let i = 0; i < s.w * s.h; i++) {
    const a = s.rgba[i * 4 + 3];
    const packed = a ? (s.rgba[i * 4] + s.rgba[i * 4 + 1] * 256 + s.rgba[i * 4 + 2] * 65536 + a * 16777216) : 0;
    if (!idx.has(packed)) { idx.set(packed, pal.length); pal.push(packed); }
    const v = idx.get(packed);
    if (v !== prev || run === 255) { flush(); prev = v; }
    run++;
  }
  flush();
  if (pal.length > 255) throw new Error(`palette overflow in ${key}`);
  sprites.push({ key, w: s.w, h: s.h, ox: s.ox, oy: s.oy, pal, data: Buffer.from(bytes).toString("base64") });
}
for (const k of ["drill", "smelter", "assembler", "generator", "lab"]) for (let d = 0; d < 4; d++) {
  for (let f = 0; f < FRAMES; f++) add(`${k}:${d}:${f}`, bake(GENOMES[k], { dir: d, phase: f / FRAMES, active: true }));
  add(`${k}:${d}:off`, bake(GENOMES[k], { dir: d, active: false }));
}
for (let f = 0; f < FRAMES; f++) add(`hub:0:${f}`, bake(GENOMES.hub, { phase: f / FRAMES }));
for (let d = 0; d < 4; d++) add(`solar:${d}:off`, bake(GENOMES.solar, { dir: d, active: false }));
add("pole:0:off", bake(GENOMES.pole, { active: false }));
for (let d = 0; d < 4; d++) for (let f = 0; f < BELT_FRAMES; f++) add(`belt:${d}:${f}`, bake(GENOMES.belt, { dir: d, phase: f / BELT_FRAMES, groundShadow: false }));
for (const g of ["grass", "grass2"]) for (let v = 0; v < 4; v++) add(`t:${g}:${v}`, bake(TILE_GENOMES[g], { groundShadow: false, outline: false, seed: v + 1 }));
for (const g of ["sand", "rock"]) for (let v = 0; v < 2; v++) add(`t:${g}:${v}`, bake(TILE_GENOMES[g], { groundShadow: false, outline: g === "rock", seed: v + 1 }));
for (let f = 0; f < 4; f++) add(`t:water:${f}`, bake(TILE_GENOMES.water, { groundShadow: false, outline: false, phase: f / 4 }));
const ORE_MATS = ["", "ore_iron", "ore_copper", "ore_coal", "ore_stone"];
for (let o = 1; o <= 4; o++) for (let v = 0; v < 3; v++) add(`ore:${o}:${v}`, bake(oreGenome(ORE_MATS[o], v + 1)));
for (const k of Object.keys(ITEM_GENOMES)) add(`item:${k}`, bake(scaleGenome(ITEM_GENOMES[k], 1.9), { groundShadow: false, shadows: false }));

let src = HEADER + `-- ${sprites.length} sprites. Decoded by Atlas.luau.\nreturn {\n\tframes = ${FRAMES}, beltFrames = ${BELT_FRAMES},\n\tsprites = {\n`;
for (const s of sprites) src += `\t\t{ key = "${s.key}", w = ${s.w}, h = ${s.h}, ox = ${s.ox}, oy = ${s.oy}, pal = { ${s.pal.join(", ")} }, data = "${s.data}" },\n`;
src += "\t},\n}\n";
fs.writeFileSync(`${RB}/src/shared/AtlasData.luau`, src);

// ---------- Fixture.luau: replay a bot session, compare hashes ----------
const st = createWorld(C, { seed: 1 });
st.log = [];
const a = starterFactory(st);
for (let i = 0; i < 120 * 60; i++) step(st);
scienceBlock(st, a.gen);
const endTick = st.tick + 120 * 60;
while (st.tick < endTick) { step(st); st.events.length = 0; }
const log = st.log.slice();
// re-run from scratch applying the log at the recorded ticks, sampling hashes
const { applyCommand } = await import("../engine/sim/factory.js");
const re = createWorld(C, { seed: 1 });
const checkpoints = [];
let li = 0;
while (re.tick < endTick) {
  while (li < log.length && log[li][0] === re.tick) { applyCommand(re, log[li].slice(1)); li++; }
  if (re.tick % 600 === 0) checkpoints.push([re.tick, stateHash(re)]);
  step(re);
  re.events.length = 0;
}
checkpoints.push([re.tick, stateHash(re)]);
if (stateHash(re) !== stateHash(st)) throw new Error("JS replay diverged from the recorded session");
const fixture = { seed: 1, terrainHash: terrainHash(re), commands: log, checkpoints, endTick };
fs.mkdirSync(`${RB}/tests`, { recursive: true });
fs.writeFileSync(`${RB}/tests/Fixture.luau`, HEADER + "return " + lua(fixture) + "\n");

const kb = n => (n / 1024).toFixed(0) + " KB";
console.log(`Content.luau ok; AtlasData.luau ${sprites.length} sprites ${kb(src.length)}; Fixture ${log.length} commands, ${checkpoints.length} checkpoints, terrainHash ${fixture.terrainHash}`);
